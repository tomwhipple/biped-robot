"""The campaign on two engines, case by case: each verdict side by side, the
largest difference in every measured number, and the floating cell inputs.

    python -m pbsim.board.crosscheck DIR_A:LABEL_A DIR_B:LABEL_B

Each DIR holds one engine's ``truth.json``, ``seq.json`` and ``sweep.json``
(``make pbfull`` writes them to ``build/power-board/fullsim``). The output is
the per-case evidence the simulation record cites.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

from .netlist import SCHEMATIC


def _load(d: Path, suite: str) -> dict[str, dict]:
    return {r["name"]: r for r in json.loads((d / f"{suite}.json").read_text())}


def _verdict(r: dict | None) -> str:
    if r is None:
        return "missing"
    if "error" in r:
        return "error"
    return "FAIL" if r["fail"] else "pass"


def _numbers(r: dict, key: str) -> dict[str, float]:
    return {k: float(v) for k, v in r.get(key, {}).items()
            if isinstance(v, (int, float)) and not isinstance(v, bool)}


def _largest_diffs(A: dict, B: dict, key: str) -> list[tuple[str, float, str]]:
    worst: dict[str, tuple[float, str]] = {}
    for name in sorted(A.keys() & B.keys()):
        a, b = _numbers(A[name], key), _numbers(B[name], key)
        for k in a.keys() & b.keys():
            d = abs(a[k] - b[k])
            if d > worst.get(k, (-1.0, ""))[0]:
                worst[k] = (d, name)
    return sorted(((k, d, n) for k, (d, n) in worst.items()), key=lambda x: -x[1])


def _floating(R: dict) -> dict[str, tuple[float, float, int]]:
    out: dict[str, list] = {}
    for r in R.values():
        for v in r.get("floating", []):
            a = out.setdefault(v["check"], [float("inf"), float("-inf"), 0])
            a[0], a[1], a[2] = min(a[0], v["lo"]), max(a[1], v["hi"]), a[2] + 1
    return {k: tuple(v) for k, v in out.items()}


def main(argv: list[str]) -> int:
    (da, la), (db, lb) = [(Path(s.rsplit(":", 1)[0]), s.rsplit(":", 1)[1])
                          for s in argv[:2]]
    p = print
    sha = hashlib.sha256(SCHEMATIC.read_bytes()).hexdigest()
    p(f"# Whole-board campaign, {la} against {lb}\n")
    p("Generated by `python -m pbsim.board.crosscheck` (pcb/power-board) from each "
      f"engine's `make pbfull` results; schematic SHA-256 {sha[:8]}…{sha[-5:]}.\n")
    for suite, key in (("truth", "measured"), ("seq", "metrics"),
                       ("sweep", "metrics")):
        A, B = _load(da, suite), _load(db, suite)
        names = sorted(A.keys() | B.keys())
        fa = sum(_verdict(A.get(n)) != "pass" for n in names)
        fb = sum(_verdict(B.get(n)) != "pass" for n in names)
        differ = [n for n in names if _verdict(A.get(n)) != _verdict(B.get(n))]
        p(f"## {suite}: {len(names)} cases; not passing: {fa} on {la}, "
          f"{fb} on {lb}; verdicts differ in {len(differ)}\n")
        if suite == "truth":
            for eng, R in ((la, A), (lb, B)):
                fl = _floating(R)
                p(f"Floating cell inputs (XT60 out, reported, not judged) on {eng}:"
                  + ("" if fl else " none"))
                for k, (lo, hi, c) in sorted(fl.items()):
                    p(f"  {k}: {lo:.2f} to {hi:.2f} V in {c} cases")
            p()
        p(f"Largest |{la} − {lb}| per measured number (case):")
        for k, d, n in _largest_diffs(A, B, key)[:12]:
            p(f"  {k}: {d:.4g} ({n})")
        p()
        p(f"{'case':<64} {la:>8} {lb:>8}")
        for n in names:
            va, vb = _verdict(A.get(n)), _verdict(B.get(n))
            p(f"{n:<64} {va:>8} {vb:>8}")
            for eng, R, v in ((la, A, va), (lb, B, vb)):
                if v != "pass" and n in R:
                    why = "; ".join(R[n].get("fail") or [R[n].get("error", "")])
                    p(f"    {eng}: {why[:300]}")
        p()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
