#!/usr/bin/env python3
"""Prerequisites for the Makefile: the repo files each Python generator reads.

    python tools/mkdeps.py imports > build/deps/py.mk   # every generator's imports
    python tools/mkdeps.py v6      > build/deps/v6.mk   # the v6 part and slice rules

The Makefile runs both itself. Like `cc -MM` for C: a generator's
prerequisites are the repo modules it imports, transitively, read from the
source (ast) rather than by running it. It errs toward extra prerequisites:
a module name maps to the one repo file of that name (no two repo modules
share one) whichever directory imports it, and `from x import y` also counts
a repo module named y when x is a repo package or the import is relative.

`v6` lists what the per-part and per-job rules need: the parts of every build
variant, read by importing cad/v6/parts_v6.py under each variant's
environment (its part builders are imported lazily, by name, so the ast walk
cannot see them), and the slice jobs of cad/v6/print_settings.json.
"""
from __future__ import annotations

import ast
import json
import os
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Every script the Makefile runs to write a file.
GENERATORS = [
    "cad/v6/parts_v6.py",
    "cad/v6/assembly_v6.py",
    "cad/v6/animate_v6.py",
    "cad/v6/render_steps_v6.py",
    "cad/parts.py",
    "cad/fasteners.py",
    "cad/servos.py",
    "cad/slice.py",
    "cad/freecad_articulate.py",
    "experiments/plan-b-bench/plan_b_rig.py",
    "experiments/plan-b-bench/plan_b_rig_v3.py",
    "sim/build_v6_inertia.py",
    "sim/add_cad_meshes.py",
    "sim/record_getup_ref.py",
    "sim/mjx/gen_terrain_mosaic.py",
    "sim/mjx/harvest_rise_states.py",
    "sim/fig_getup_noappendage.py",
    "sim/render_link_demo.py",
    "tools/gen_protocol_vectors.py",
]

# The environment that puts each build variant's own parts in parts_v6.PARTS.
VARIANTS = [
    {"ARMS": "1", "HIP_YOKE_VARIANT": "single", "SERVO_PLAN": "hips"},   # the robot to print
    {"HIP_YOKE_VARIANT": "glued"},
    {"HIP_YOKE_VARIANT": "split"},
    {"ARMS": "0"},
]

V6_STL = "cad/v6/stl"
SETTINGS = "cad/v6/print_settings.json"


def repo_modules():
    out = subprocess.run(["git", "ls-files", "-co", "--exclude-standard", "--", "*.py"],
                         cwd=ROOT, capture_output=True, text=True, check=True).stdout.split()
    index = {}
    for path in out:
        if not os.path.exists(os.path.join(ROOT, path)):
            continue
        stem = os.path.splitext(os.path.basename(path))[0]
        if stem == "__init__":
            stem = os.path.basename(os.path.dirname(path))
        index.setdefault(stem, path)
    return index


def imported_names(path, index):
    with open(os.path.join(ROOT, path)) as fh:
        tree = ast.parse(fh.read(), path)
    names = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for a in node.names:
                names.update(a.name.split("."))
        elif isinstance(node, ast.ImportFrom):
            pkg = node.module.split(".") if node.module else []
            names.update(pkg)
            # `from build123d import export_step` names an attribute, not cad/export_step.py
            if node.level or (pkg and pkg[0] in index):
                names.update(a.name for a in node.names)
        elif (isinstance(node, ast.Call) and node.args
              and isinstance(node.args[0], ast.Constant) and isinstance(node.args[0].value, str)
              and ((isinstance(node.func, ast.Name) and node.func.id == "__import__")
                   or (isinstance(node.func, ast.Attribute) and node.func.attr == "import_module"))):
            names.add(node.args[0].value)
    return names


class Graph:
    def __init__(self):
        self.index = repo_modules()
        self.direct = {}

    def deps(self, path):
        """``path`` and every repo module it imports, transitively."""
        seen, todo = set(), [path]
        while todo:
            p = todo.pop()
            if p in seen:
                continue
            seen.add(p)
            if p not in self.direct:
                self.direct[p] = {self.index[n] for n in imported_names(p, self.index)
                                  if n in self.index}
            todo.extend(self.direct[p])
        return seen


def var(name, files):
    return f"{name} := {' '.join(sorted(files))}"


def imports():
    g = Graph()
    print("# GENERATED by tools/mkdeps.py imports -- do not edit")
    for gen in GENERATORS:
        print(var(f"PYDEPS_{gen}", g.deps(gen)))


def list_parts(env):
    code = (
        "import json, os, sys\n"
        "sys.path.insert(0, os.path.join(sys.argv[1], 'cad', 'v6'))\n"
        "import parts_v6 as P\n"
        "rows = [(n, f) for n, f, *_ in P.PARTS] + [(n, f) for n, f, _ in P.REFERENCE]\n"
        "print(json.dumps([(n, f.__name__.split('.')[0] if '.' in f.__name__ else f.__module__)"
        " for n, f in rows]))\n"
    )
    run = subprocess.run([sys.executable, "-c", code, ROOT], cwd=ROOT, capture_output=True,
                         text=True, env=dict(os.environ, **env))
    if run.returncode:
        raise RuntimeError(f"importing cad/v6/parts_v6.py with {env} failed: "
                           + run.stderr.strip().splitlines()[-1])
    return json.loads(run.stdout.strip().splitlines()[-1])


def v6():
    g = Graph()
    try:
        with ThreadPoolExecutor(len(VARIANTS)) as pool:
            listings = list(pool.map(list_parts, VARIANTS))
    except RuntimeError as e:
        # A machine without the CAD stack can still run every other target.
        print("# GENERATED by tools/mkdeps.py v6 -- do not edit")
        print(f"V6_DEPS_ERROR := {e}")
        return
    module, env = {}, {}
    for variant, rows in zip(VARIANTS, listings):
        for name, mod in rows:
            if name not in module:
                module[name] = mod
                if variant is not VARIANTS[0]:
                    env[name] = " ".join(f"{k}={v}" for k, v in variant.items())
    default = [n for n, _ in listings[0]]
    extra = [n for n in module if n not in default]

    print("# GENERATED by tools/mkdeps.py v6 -- do not edit")
    print(var("V6_PARTS", default))
    print(var("V6_VARIANT_PARTS", extra))
    for name in extra:
        print(f"PART_ENV_{name} := {env[name]}")
    base = g.deps("cad/v6/parts_v6.py")
    rollup = set(base)
    for name, mod in module.items():
        files = base | g.deps(g.index[mod])
        if name in default:
            rollup |= files
        print(var(f"PARTDEPS_{name}", files))
    print(var("V6_ROLLUP_DEPS", rollup))

    with open(os.path.join(ROOT, SETTINGS)) as fh:
        spec = json.load(fh)
    slice_deps = g.deps("cad/slice.py") | {SETTINGS}
    jobs = []
    for variant, entry in [(None, spec)] + sorted(spec.get("variants", {}).items()):
        plates = entry.get("plates", {})
        on_plates = {p for plate in plates.values() for p in plate["parts"]}
        for job in sorted(plates) + sorted(p for p in entry.get("parts", {}) if p not in on_plates):
            parts = plates[job]["parts"] if job in plates else [job]
            unknown = [p for p in parts if p not in module]
            if unknown:
                print(f"mkdeps: slice job {job}: no v6 part {', '.join(unknown)}; skipped",
                      file=sys.stderr)
                continue
            jobs.append(job)
            if variant:
                print(f"SLICE_FLAGS_{job} := --variant {variant}")
            print(var(f"JOBDEPS_{job}", slice_deps | {f"{V6_STL}/{p}.stl" for p in parts}))
    print(var("V6_SLICE_JOBS", jobs))


if __name__ == "__main__":
    {"imports": imports, "v6": v6}[sys.argv[1]]()
