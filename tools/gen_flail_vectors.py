#!/usr/bin/env python3
"""Freeze the first policy-stand failure into a replay fixture for the flail guard.

Run:  python3 tools/gen_flail_vectors.py [--csv <ticks.csv>] [--seconds 4.0]

2026-11-01 21:39 UTC: the first armed policy stand (robot_legs_walk14_s1_s128r24)
stood ~3.3 s, then its targets chattered and swung until the operator tilted the
robot past the fall guard. The flight recording lives in hw_sessions/ (gitignored,
main checkout); this writes the armed (source ctrl) ticks of its first --seconds
into firmware/host/vectors/flail_vectors.h -- per tick the IMU validity, up vector
and gyro, the 12 WRITTEN targets (goal_rad: after the shaper and the takeover ramp)
and the 12 RAW policy targets (nom_rad: the action through the action map) -- so
firmware/host/test_flailguard.cpp can assert, against the real thing, that the
guard (firmware/components/flailguard) stays quiet through the clean first 3 s
and trips by 3.5 s.

The CSV is `tools/flight_reader.py csv` output. Stdlib only.
"""
import argparse
import csv
import math
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "firmware", "host", "vectors", "flail_vectors.h")
STEM = "flight_20261101T213631Z_policy_stand1"
# The v6 legs policy's joint order (firmware/policies/v6legs/obs/obs_spec.h).
JOINTS = ("L_hip_yaw", "L_hip_roll", "L_hip_pitch", "L_knee", "L_ankle", "L_ankle_roll",
          "R_hip_yaw", "R_hip_roll", "R_hip_pitch", "R_knee", "R_ankle", "R_ankle_roll")
TF_IMU_VALID = 16      # tools/flightrec.py


def main_checkout() -> str:
    try:
        common = subprocess.run(["git", "-C", ROOT, "rev-parse", "--path-format=absolute",
                                 "--git-common-dir"], capture_output=True, text=True,
                                timeout=5, check=True).stdout.strip()
        return os.path.dirname(common)
    except (OSError, subprocess.SubprocessError):
        return ROOT


def fmt(x: float) -> str:
    s = f"{x:.6g}"
    if not any(c in s for c in ".en"):
        s += ".0"                        # "1f" is not a C++ literal; "1.0f" is
    return s + "f"


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--csv", default=os.path.join(main_checkout(), "hw_sessions", "2026-11-01",
                                                 STEM + "_ticks.csv"))
    p.add_argument("--seconds", type=float, default=4.0)
    p.add_argument("--out", default=OUT)
    a = p.parse_args(argv)
    rows = [r for r in csv.DictReader(open(a.csv)) if r["source"] == "ctrl"]
    if not rows:
        sys.exit(f"{a.csv}: no armed (ctrl) ticks")
    t0 = float(rows[0]["t_utc"])
    ticks = []
    for r in rows:
        t = float(r["t_utc"]) - t0
        if t > a.seconds + 1e-6:
            break
        vals = [float(r[f"{j}.goal_rad"]) for j in JOINTS] + [float(r[f"{j}.nom_rad"]) for j in JOINTS]
        if not all(math.isfinite(v) for v in vals):
            sys.exit(f"tick {r['tick']}: a non-finite target -- not the recording this expects")
        cmd = [float(r[f"cmd{i}"]) for i in range(7)]
        ticks.append(dict(
            t=t, tick=int(r["tick"]), valid=bool(int(r["flags"]) & TF_IMU_VALID),
            up=[float(r[f"up_{c}"]) for c in "xyz"], gyro=[float(r[f"gyro_{c}"]) for c in "xyz"],
            target=vals[:12], raw=vals[12:], cmd=cmd))
    lines = [
        "// GENERATED by tools/gen_flail_vectors.py -- do not edit.",
        f"// Source: hw_sessions/2026-11-01/{STEM}_ticks.csv (armed ticks, first {a.seconds:g} s).",
        "// The first armed policy stand, 2026-11-01 21:39 UTC: clean ~3.3 s, then the",
        "// policy flailed. Angles in rad (policy joint frame), gyro rad/s, t s from the arm.",
        "#pragma once",
        "",
        "namespace flailvec {",
        "",
        f"inline constexpr int kNumJoints = {len(JOINTS)};",
        "inline constexpr const char* kJointNames[kNumJoints] = {"
        + ", ".join(f'"{j}"' for j in JOINTS) + "};",
        "",
        "struct Tick {",
        "    float t;            // s since the first armed tick",
        "    unsigned tick;      // the firmware's tick counter",
        "    bool imu_valid;",
        "    float up[3];",
        "    float gyro[3];",
        "    float target[kNumJoints];   // written goal (goal_rad)",
        "    float raw[kNumJoints];      // raw policy target (nom_rad)",
        "    float cmd[7];               // vx vy wz crouch lift foot_dx foot_dz",
        "};",
        "",
        f"inline constexpr int kNumTicks = {len(ticks)};",
        "inline constexpr Tick kTicks[kNumTicks] = {",
    ]
    for k in ticks:
        lines.append(
            f"    {{{fmt(k['t'])}, {k['tick']}u, {'true' if k['valid'] else 'false'}, "
            f"{{{', '.join(fmt(v) for v in k['up'])}}}, {{{', '.join(fmt(v) for v in k['gyro'])}}},\n"
            f"     {{{', '.join(fmt(v) for v in k['target'])}}},\n"
            f"     {{{', '.join(fmt(v) for v in k['raw'])}}},\n"
            f"     {{{', '.join(fmt(v) for v in k['cmd'])}}}}},")
    lines += ["};", "", "}  // namespace flailvec", ""]
    with open(a.out, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {a.out}: {len(ticks)} ticks, {ticks[-1]['t']:.2f} s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
