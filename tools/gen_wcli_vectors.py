#!/usr/bin/env python3
"""Freeze link/wcliproto.py's encoder into golden vectors for the C++ port.

Run:  .venv/bin/python tools/gen_wcli_vectors.py     (or `make vectors`)

The Wi-Fi CLI wire format is written twice: in Python on mira (the client,
link/wcliproto.py -- the reference) and in C++ on the robot
(firmware/components/wcli). This writes the key derivation and, per case, the
fields and the bytes Python produced into firmware/host/vectors/wcli_vectors.h;
firmware/host/test_wcli.cpp encodes the fields and asserts the same bytes,
and decodes the bytes back. A moved field, a different MAC input or a
different key label fails there, not on the bench.

The key is a fixed test pattern -- never a real robot's key.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "link"))

import wcliproto as W  # noqa: E402

OUT = os.path.join(ROOT, "firmware", "host", "vectors", "wcli_vectors.h")

KEY = bytes(range(0x40, 0x60))   # 32 bytes, obviously not random

# (name, client->robot?, type, sid, seq, aux, flags, payload)
CASES = [
    ("hello", True, W.T_HELLO, 0x0123456789ABCDEF, 0, 0, 0, b""),
    ("cmd_ping", True, W.T_CMD, 0xF00DFACE12345678, 7, 0, 0, b"ping"),
    ("cmd_pose", True, W.T_CMD, 0xF00DFACE12345678, 0x01020304, 0, 0,
     b"pose 2048 2048 2048 2048 2048 2048 2048 2048 2048 2048 s1500 BL"),
    ("cancel", True, W.T_CANCEL, 0xF00DFACE12345678, 9, 0, 0, b""),
    ("poll_resend", True, W.T_POLL, 0xF00DFACE12345678, 0, 0xA0B0C0D0,
     W.POLL_RESEND, b""),
    ("challenge", False, W.T_CHALLENGE, 0x1122334455667788, 0, 0, 0,
     (0x0123456789ABCDEF).to_bytes(8, "little")),
    ("out_done", False, W.T_OUT, 0x1122334455667788, 42, 7,
     W.OUT_DONE | W.OUT_REFUSED,
     b"refused over Wi-Fi (tether only): `id` assigns a servo ID\r\n"),
    ("out_full", False, W.T_OUT, 0x1122334455667788, 43, 0, W.OUT_ASYNC,
     bytes((0x20 + i % 95) for i in range(W.MAX_CHUNK))),
    ("status", False, W.T_STATUS, 0x1122334455667788, 44, 7,
     W.ST_DONE | W.ST_LAGGING, (12).to_bytes(4, "little")),
    ("stale", False, W.T_STALE, 0x0BADC0DE0BADC0DE, 0, 0, 0, b""),
]


def cbytes(b: bytes) -> str:
    if not b:
        return "{0}"
    rows = []
    for i in range(0, len(b), 16):
        rows.append("    " + ", ".join(f"0x{x:02X}" for x in b[i:i + 16]))
    return "{\n" + ",\n".join(rows) + "}"


def main():
    keys = W.derive_keys(KEY)
    out = ["// GENERATED by tools/gen_wcli_vectors.py -- do not edit.",
           "// Source of truth: link/wcliproto.py (the Wi-Fi CLI client).",
           "#pragma once",
           "#include <stddef.h>",
           "#include <stdint.h>",
           "",
           "namespace wcli_vectors {",
           "",
           f"constexpr uint8_t kKey[32] = {cbytes(KEY)};",
           f"constexpr uint8_t kC2R[32] = {cbytes(keys.c2r)};",
           f"constexpr uint8_t kR2C[32] = {cbytes(keys.r2c)};",
           ""]
    names = []
    for name, c2r, typ, sid, seq, aux, flags, payload in CASES:
        wire = W.encode(W.Msg(typ, sid, seq, aux, flags, payload),
                        keys.c2r if c2r else keys.r2c)
        out.append(f"constexpr uint8_t k_{name}_payload[] = {cbytes(payload)};")
        out.append(f"constexpr uint8_t k_{name}_wire[] = {cbytes(wire)};")
        names.append((name, c2r, typ, sid, seq, aux, flags, len(payload),
                      len(wire)))
    out += ["",
            "struct Case {",
            "    const char* name;",
            "    bool c2r;",
            "    uint8_t type;",
            "    uint64_t sid;",
            "    uint32_t seq, aux;",
            "    uint16_t flags, len;",
            "    const uint8_t* payload;",
            "    const uint8_t* wire;",
            "    size_t wire_len;",
            "};",
            "",
            "constexpr Case kCases[] = {"]
    for name, c2r, typ, sid, seq, aux, flags, plen, wlen in names:
        out.append(f"    {{\"{name}\", {'true' if c2r else 'false'}, 0x{typ:02X}, "
                   f"0x{sid:016X}ull, {seq}u, {aux}u, {flags}, {plen}, "
                   f"k_{name}_payload, k_{name}_wire, {wlen}}},")
    out += ["};", "", "}  // namespace wcli_vectors", ""]
    text = "\n".join(out)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
